"""Run the 6-page live demo set (CLAUDE.md Section 13) and save REAL outputs to examples/.

    cp scripts/demo_urls.example.json scripts/demo_urls.json   # fill in real URLs you are allowed to audit
    python scripts/demo_set.py

Outputs examples/<slug>/report.{md,json} and examples/INDEX.md. These files are for the README only;
the app never reads them. One audit = a handful of requests; the script waits between audits.
"""
import asyncio
import json
import re
import sys
from pathlib import Path

from citegap.config import load_dotenv, load_settings
from citegap.pipeline import run_audit
from citegap.report.render_md import render_markdown, verdict
from citegap.store import Store

ROOT = Path(__file__).resolve().parents[1]


async def main() -> int:
    load_dotenv()
    s = load_settings()
    cfg = ROOT / "scripts" / "demo_urls.json"
    if not s.tinyfish_api_key or not cfg.exists():
        print("Need TINYFISH_API_KEY and scripts/demo_urls.json (copy demo_urls.example.json).")
        return 2
    store = Store(s.db_path)
    index = ["# Real demo audits\n", "Generated by `scripts/demo_set.py` from live TinyFish calls. Not read by the app.\n",
             "| Failure mode | URL | ARS | SVS | Verdict |\n|---|---|---|---|---|"]
    for item in json.loads(cfg.read_text()):
        slug = re.sub(r"[^a-z0-9]+", "-", item["label"].lower()).strip("-")
        print(f"auditing {item['label']}: {item['url']}")
        try:
            rep = await run_audit(item["url"], item.get("query"), settings=s, store=store, emit=lambda e: None)
        except Exception as exc:  # keep going; record the failure honestly
            index.append(f"| {item['label']} | {item['url']} | - | - | audit failed: {type(exc).__name__} |")
            continue
        store.save(rep)
        d = ROOT / "examples" / slug
        d.mkdir(parents=True, exist_ok=True)
        (d / "report.md").write_text(render_markdown(rep), encoding="utf-8")
        (d / "report.json").write_text(rep.model_dump_json(indent=2), encoding="utf-8")
        index.append(f"| {item['label']} | {item['url']} | {rep.ars.total:.0f} | {rep.svs.total:.0f} | {verdict(rep)} |")
        await asyncio.sleep(20)  # be polite; also respects the 5/min Search limit
    (ROOT / "examples" / "INDEX.md").write_text("\n".join(index) + "\n", encoding="utf-8")
    print("wrote examples/INDEX.md")
    return 0


if __name__ == "__main__":
    sys.exit(asyncio.run(main()))
